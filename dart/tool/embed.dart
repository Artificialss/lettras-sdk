// Regenerates lib/src/engine_data.dart from ../mcp/engine/lettras_engine.wasm (or the path given as the first argument).
//   dart run tool/embed.dart [path/to/lettras_engine.wasm]
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final source = File(args.isNotEmpty ? args.first : '../mcp/engine/lettras_engine.wasm');
  final out = File('lib/src/engine_data.dart');
  final b64 = base64.encode(source.readAsBytesSync());
  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/embed.dart: the compiled Lettras engine (proprietary, see ENGINE-LICENSE) as base64.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln("const String engineBase64 = '$b64';");
  out.writeAsStringSync(buffer.toString());
  stdout.writeln('wrote ${out.path} (${b64.length ~/ 1024} KB)');
}
